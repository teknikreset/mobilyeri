def _more():
    r = []
    # bölme
    for b in range(3, 13):
        for q in range(6, 25):
            if (len(r)) % 2 == 0 or b % 2 == 1:
                r.append(("%d / %d kaçtır?" % (b * q, b), (str(q),)))
    # iki rakamlı çarpma
    for a, b in [(a, b) for a in range(12, 50, 4) for b in range(12, 30, 3)]:
        r.append(("%d x %d kaçtır?" % (a, b), (str(a * b),)))
    # yüzde
    for a in range(1, 11):
        r.append(("100'nün %d%%'si kaçtır?" % (a * 10), (str(a * 10),)))
    # daha çok çarpma: 3..19 x 3..19 geniş
    for a in range(3, 20):
        for b in range(a, 20):
            if (a + b) % 4 == 0:
                r.append(("%d x %d kaçtır?" % (a, b), (str(a * b),)))
    # toplama grid
    for a in range(5, 40, 2):
        for b in range(8, 40, 3):
            r.append(("%d + %d kaçtır?" % (a, b), (str(a + b),)))
    # ek çarpma
    for a in range(3, 31):
        for b in range(3, 7):
            if (a * b) % 2 == 0:
                r.append(("%d x %d kaçtır?" % (a, b), (str(a * b),)))
    # yarısı
    for x in range(20, 200, 7):
        r.append(("%d sayısının yarısı kaçtır?" % x, (str(x // 2),)))
    # büyük toplam
    for a in range(90, 130):
        for b in range(12, 40, 2):
            if (a + b) % 3 == 0:
                r.append(("%d + %d kaçtır?" % (a, b), (str(a + b),)))
    # kare 26..35
    for a in range(26, 36):
        r.append(("%d sayısının karesi kaçtır?" % a, (str(a * a),)))
    return r

