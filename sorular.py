def _math():
    r = []
    # çarpma (3..20)x(3..12) iki yön
    pair = []
    for a in range(3, 21):
        for b in range(3, 13):
            if b >= a - 2:  # yön tekrarını azalt
                pair.append((a, b))
    for a, b in pair:
        r.append(("%d x %d kaçtır?" % (a, b), (str(a * b),)))
    # toplama
    for a, b in [(a, b) for a in range(11, 90, 7) for b in range(13, 80, 9)]:
        r.append(("%d + %d kaçtır?" % (a, b), (str(a + b),)))
    # çıkarma
    for a, b in [(a, b) for a in range(50, 130, 6) for b in range(11, 49, 7)]:
        r.append(("%d - %d kaçtır?" % (a, b), (str(a - b),)))
    # kare
    for a in range(6, 26):
        r.append(("%d sayısının karesi kaçtır?" % a, (str(a * a),)))
    # basit iki adım
    for a, b, c in [(a, b, a + b + c) for a in range(4, 15) for b in range(5, 16) for c in range(6, 14)][::3]:
        r.append(("%d + %d + %d kaçtır?" % (a, b, c), (str(a + b + c),)))
    return r

